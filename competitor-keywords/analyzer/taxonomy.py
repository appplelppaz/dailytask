def _variants_index() -> list[tuple[str, str, str]]:
    """(正規化済み表記, カテゴリー, 代表語) を、長い語から順に並べる。"""
    rows = []
    for cat, terms in CATEGORIES.items():
        for canon, variants in terms.items():
            for v in variants:
                rows.append((normalize(v), cat, canon))
    rows.sort(key=lambda r: len(r[0]), reverse=True)
    return rows


_INDEX = _variants_index()


def classify(keyword: str) -> dict[str, list[str]]:
    """キーワードに含まれる語を辞書と照合し、{カテゴリー: [代表語...]} を返す。

    長い語から先に照合し、同じカテゴリー内では照合済みの文字列部分を再利用しない
    (「スクエアトゥ」が「スクエア」と二重に数えられないようにするため)。
    カテゴリーが違えば同じ部分を使ってよい(「就活パンプス」→ アイテム と 用途)。
    """
    text = normalize(keyword)
    found: dict[str, list[str]] = {}

    def add(cat: str, canon: str) -> None:
        found.setdefault(cat, [])
        if canon not in found[cat]:
            found[cat].append(canon)

    masked: dict[str, str] = {}
    tokens = set(text.split(" "))
    for variant, cat, canon in _INDEX:
        if not variant:
            continue
        # 「ca」のような短い英字は単語として一致した場合のみ(casual 等への誤爆防止)
        if len(variant) <= 3 and variant.isascii() and variant.isalpha():
            if variant in tokens:
                add(cat, canon)
            continue
        m = masked.get(cat, text)
        if variant in m:
            add(cat, canon)
            masked[cat] = m.replace(variant, "\0" * len(variant))

    for m in _CM.finditer(text):
        val = float(m.group(1))
        if 19 <= val <= 28:
            add("サイズ", f"{m.group(1)}cm")
        elif val <= 15:
            add("ヒール", f"ヒール{m.group(1)}cm")
    for m in _AGE.finditer(text):
        add("年代", f"{m.group(1)}0代")
    for m in _YEN.finditer(text):
        add("価格帯", f"{m.group(1)}円")
    for m in _WIDTH.finditer(text):
        canon = {"3": "3E", "4": "4E"}.get(m.group(1), "5E以上" if m.group(1) in "56" else "ワイズ")
        add("幅", canon)
    return found


def brand_in(keyword: str, extra_brands: list[str] | None = None) -> str | None:
    text = normalize(keyword)
    tokens = set(text.split(" "))
    for b in list(KNOWN_BRANDS) + list(extra_brands or []):
        nb = normalize(b)
        if not nb:
            continue
        # 短いアルファベット(gu, ing 等)は語として一致した場合のみ
        if len(nb) <= 3 and nb.isascii():
            if nb in tokens:
                return b
        elif nb in text:
            return b
    return None


def rule_intent(keyword: str, extra_brands: list[str] | None = None) -> str:
    """ルールによる検索意図の推定。返り値は INTENT_LABELS のキー。"""
    if brand_in(keyword, extra_brands):
        return "navigational"
    text = normalize(keyword)
    for intent, words in _INTENT_RULES:
        if any(normalize(w) in text for w in words):
            return intent
    # 「幅広 パンプス」のような 属性+アイテム の組み合わせは、商品を探している検索とみなす
    return "commercial"


def feature_categories() -> list[str]:
    """商品企画の観点で集計するカテゴリー(アイテムは除く)。"""
    return [c for c in CATEGORIES if c != "アイテム"]


def query_word(category: str, canon: str) -> str:
    """検索キーワードを組み立てるときの表記(代表語の最初の表記)。"""
    variants = CATEGORIES.get(category, {}).get(canon)
    if variants:
        return variants[0]
    if canon.startswith("ヒール") and canon.endswith("cm"):
        return canon[len("ヒール"):] + " ヒール"
    return canon


def format_categories(cats: dict[str, list[str]]) -> str:
    return " / ".join(f"{c}:{'・'.join(t)}" for c, t in cats.items() if c != "アイテム")
